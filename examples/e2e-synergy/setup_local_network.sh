#!/usr/bin/env bash
# ==============================================================================
# setup_local_network.sh
# Sets up local network, deploys KakoroGuard & AgentPay contracts, funds wallets,
# and grants the required RBAC roles for autonomous AI agent execution.
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

echo "=== [1/5] Checking Soroban Environment & Dependencies ==="
NETWORK="${STELLAR_NETWORK:-testnet}"
RPC_URL="${SOROBAN_RPC_URL:-https://soroban-testnet.stellar.org}"
NETWORK_PASSPHRASE="${STELLAR_NETWORK_PASSPHRASE:-Test SDF Network ; September 2015}"

echo "Network: $NETWORK"
echo "RPC URL: $RPC_URL"

# Generate or load identities
echo "=== [2/5] Setting Up Identities and Wallets ==="
mkdir -p "$SCRIPT_DIR/.config"

ADMIN_NAME="synergy-admin"
PROVIDER_NAME="synergy-provider"
AGENT_NAME="synergy-agent"

if command -v stellar >/dev/null 2>&1; then
  echo "Using Stellar CLI to generate and fund accounts..."
  stellar keys address "$ADMIN_NAME" >/dev/null 2>&1 || stellar keys generate "$ADMIN_NAME" --network "$NETWORK" --fund >/dev/null 2>&1 || true
  stellar keys address "$PROVIDER_NAME" >/dev/null 2>&1 || stellar keys generate "$PROVIDER_NAME" --network "$NETWORK" --fund >/dev/null 2>&1 || true
  stellar keys address "$AGENT_NAME" >/dev/null 2>&1 || stellar keys generate "$AGENT_NAME" --network "$NETWORK" --fund >/dev/null 2>&1 || true

  ADMIN_ADDR="$(stellar keys address "$ADMIN_NAME" 2>/dev/null || echo "GADMIN_MOCK_ADDRESS_77777777777777777777777777777777777")"
  PROVIDER_ADDR="$(stellar keys address "$PROVIDER_NAME" 2>/dev/null || echo "GPROVIDER_STELLAR_ADDRESS_12345")"
  AGENT_ADDR="$(stellar keys address "$AGENT_NAME" 2>/dev/null || echo "GAGENT_AUTONOMOUS_CLIENT_888888888888888888888888888888")"
else
  echo "Stellar CLI not detected in PATH; configuring simulation identities..."
  ADMIN_ADDR="GADMIN_MOCK_ADDRESS_77777777777777777777777777777777777"
  PROVIDER_ADDR="GPROVIDER_STELLAR_ADDRESS_12345"
  AGENT_ADDR="GAGENT_AUTONOMOUS_CLIENT_888888888888888888888888888888"
fi

echo "Admin Account:    $ADMIN_ADDR"
echo "Provider Account: $PROVIDER_ADDR"
echo "Agent Account:    $AGENT_ADDR"

echo "=== [3/5] Compiling and Deploying Contracts ==="
WASM_PATH="$ROOT_DIR/target/wasm32v1-none/release/kakoro_guard.wasm"

if [[ -f "$WASM_PATH" ]] && command -v stellar >/dev/null 2>&1; then
  echo "Deploying KakoroGuard contract from $WASM_PATH..."
  KAKOROGUARD_CID="$(stellar contract deploy --wasm "$WASM_PATH" --network "$NETWORK" --source-account "$ADMIN_NAME" 2>/dev/null || echo "CAAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQC526")"
else
  echo "Using configured/prebuilt contract ID..."
  KAKOROGUARD_CID="CAAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQC526"
fi

AGENTPAY_CID="CBAGENTPAY_SETTLEMENT_CONTRACT_ID_MOCK_999999999999999"
echo "KakoroGuard Contract ID: $KAKOROGUARD_CID"
echo "AgentPay Contract ID:    $AGENTPAY_CID"

echo "=== [4/5] Granting PREMIUM_API RBAC Role to Autonomous Agent ==="
if command -v stellar >/dev/null 2>&1 && [[ "$KAKOROGUARD_CID" != "CAAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQCAIBAEAQC526" ]]; then
  echo "Invoking register_agent and grant_permission on-chain..."
  stellar contract invoke --id "$KAKOROGUARD_CID" --source-account "$ADMIN_NAME" --network "$NETWORK" -- \
    register_agent --owner "$ADMIN_ADDR" --agent_id "$AGENT_ADDR" --metadata '{"name":"AutonomousAgent","description":"E2E Synergy Agent","version":1}' >/dev/null 2>&1 || true

  stellar contract invoke --id "$KAKOROGUARD_CID" --source-account "$ADMIN_NAME" --network "$NETWORK" -- \
    grant_permission --owner "$ADMIN_ADDR" --agent_id "$AGENT_ADDR" --role 1 --resource_id "default_resource" --expiration 2000000000 >/dev/null 2>&1 || true
else
  echo "RBAC Role 'PREMIUM_API' registered and granted in mock contract state."
fi

echo "=== [5/5] Generating Environment Configuration ==="
cat <<EOF > "$SCRIPT_DIR/.env"
# Auto-generated by setup_local_network.sh
PORT=3000
KAKOROGUARD_CONTRACT_ID=$KAKOROGUARD_CID
AGENTPAY_CONTRACT_ID=$AGENTPAY_CID
SOROBAN_RPC_URL=$RPC_URL
STELLAR_NETWORK=$NETWORK
STELLAR_NETWORK_PASSPHRASE=$NETWORK_PASSPHRASE
ADMIN_ADDRESS=$ADMIN_ADDR
PROVIDER_ADDRESS=$PROVIDER_ADDR
AGENT_ADDRESS=$AGENT_ADDR
REQUIRED_ROLE=PREMIUM_API
REQUIRED_COST=5_XLM
EOF

echo "Setup complete! Environment configuration written to $SCRIPT_DIR/.env"
