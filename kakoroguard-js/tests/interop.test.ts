import { describe, it } from "node:test";
import assert from "node:assert";
import { execSync } from "node:child_process";
import {
  hashSynergisticPayload,
  serializeSynergisticPayload,
  verifySignature,
} from "../dist/esm/verifier.js";

describe("Cross-SDK Interoperability (kakoroguard-py -> kakoroguard-js)", () => {
  it("verifies request signature generated by kakoroguard-py", () => {
    // Generate signature using Python SDK
    const pythonCmd = `python -c "import json; from kakoroguard import AgentKeypair, generate_auth_header; kp = AgentKeypair.generate(); payload = {'service': 'soroban-agent', 'tier': 'premium', 'params': {'retries': 3, 'enabled': True}}; auth = generate_auth_header(payload, kp); print(json.dumps({'pub': auth.public_key, 'ts': auth.timestamp, 'sig': auth.signature, 'payload': payload}))"`;

    const output = execSync(pythonCmd, {
      cwd: "../kakoroguard-py",
      encoding: "utf-8",
    });

    const parsed = JSON.parse(output.trim()) as {
      pub: string;
      ts: number;
      sig: string;
      payload: unknown;
    };

    assert.ok(parsed.pub.startsWith("G"));
    assert.strictEqual(parsed.sig.length, 128);

    // Verify in TypeScript SDK
    const isValid = verifySignature(parsed.pub, parsed.payload, parsed.sig, parsed.ts, {
      currentTimeMs: parsed.ts,
    });

    assert.strictEqual(isValid, true, "TypeScript SDK must verify signature produced by Python SDK");
  });

  it("produces identical synergistic serialization and SHA-256 hash across Python and TypeScript", () => {
    const pythonCmd = `python -c "import json; from kakoroguard import serialize_synergistic_payload, hash_synergistic_payload; p = {'action': 'query', 'dataset': 'alpha'}; pi = {'amount': '5_XLM', 'asset': 'XLM', 'max_fee': 100000, 'destination': 'GPROV'}; s = serialize_synergistic_payload(p, pi); h = hash_synergistic_payload(p, pi); print(json.dumps({'serial': s, 'hash': h}))"`;

    const output = execSync(pythonCmd, {
      cwd: "../kakoroguard-py",
      encoding: "utf-8",
    });

    const pyResult = JSON.parse(output.trim()) as { serial: string; hash: string };

    const payload = { action: "query", dataset: "alpha" };
    const paymentIntent = {
      amount: "5_XLM",
      asset: "XLM",
      max_fee: 100_000,
      destination: "GPROV",
    };

    const tsSerial = serializeSynergisticPayload(payload, paymentIntent);
    const tsHash = hashSynergisticPayload(payload, paymentIntent);

    assert.strictEqual(tsSerial, pyResult.serial, "Serialized canonical JSON must match identically");
    assert.strictEqual(tsHash, pyResult.hash, "Deterministic SHA-256 hash must match identically");
  });
});
