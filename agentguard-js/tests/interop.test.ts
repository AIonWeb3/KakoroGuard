import { describe, it } from "node:test";
import assert from "node:assert";
import { execSync } from "node:child_process";
import { verifySignature } from "../dist/esm/verifier.js";

describe("Cross-SDK Interoperability (agentguard-py -> agentguard-js)", () => {
  it("verifies request signature generated by agentguard-py", () => {
    // Generate signature using Python SDK
    const pythonCmd = `python -c "import json; from agentguard import AgentKeypair, generate_auth_header; kp = AgentKeypair.generate(); payload = {'service': 'soroban-agent', 'tier': 'premium', 'params': {'retries': 3, 'enabled': True}}; auth = generate_auth_header(payload, kp); print(json.dumps({'pub': auth.public_key, 'ts': auth.timestamp, 'sig': auth.signature, 'payload': payload}))"`;

    const output = execSync(pythonCmd, {
      cwd: "../agentguard-py",
      encoding: "utf-8",
    });

    const parsed = JSON.parse(output.trim()) as {
      pub: string;
      ts: number;
      sig: string;
      payload: unknown;
    };

    assert.ok(parsed.pub.startsWith("G"));
    assert.strictEqual(parsed.sig.length, 128);

    // Verify in TypeScript SDK
    const isValid = verifySignature(parsed.pub, parsed.payload, parsed.sig, parsed.ts, {
      currentTimeMs: parsed.ts,
    });

    assert.strictEqual(isValid, true, "TypeScript SDK must verify signature produced by Python SDK");
  });
});
